using System;
using System.Collections.Generic;
using System.Reflection;
using HarmonyLib;

namespace ShopTogether {
    // These native stories quote funds before a later dialogue line deducts them.
    // Keep their original amounts and effects; serialize competing spending until
    // the host finishes that conversation instead of implementing its accounting.
    internal static class DialoguePayment {
        static readonly Dictionary<MethodInfo,bool> payments = new Dictionary<MethodInfo,bool>();
        static bool KnownStory(MethodInfo method) {
            var type = method.DeclaringType;
            while (type != null && type.IsNested) type = type.DeclaringType;
            string name = method.Name;
            return type == typeof(StoreClientUniqueList) && (name.StartsWith("<CreateGeorgioLoan>", StringComparison.Ordinal)||name.StartsWith("<CreateGeorgioAssistance>",StringComparison.Ordinal)) ||
                type == typeof(StoreClientList) && name.StartsWith("<",StringComparison.Ordinal) ||
                type == typeof(StoreClientListStory) && (name.StartsWith("<CreateStoryAppraisalBoard>",StringComparison.Ordinal)||name.StartsWith("<CreateStoryAppraisalBoard2>",StringComparison.Ordinal)) ||
                type == typeof(StoreClientDialogList) && (name.StartsWith("<SecurityDialogInspectionLastLine>",StringComparison.Ordinal)||name.StartsWith("<SecurityDialogInspectionFine>",StringComparison.Ordinal)) ||
                type == typeof(StoreClientListSecurity) && name.StartsWith("<GraftFineDialogue>",StringComparison.Ordinal) ||
                type == typeof(StoreClientListSpec) && (name.StartsWith("<CreateBlackmailer>",StringComparison.Ordinal)||name.StartsWith("<CreateChemicalFeedbackClient>",StringComparison.Ordinal)) ||
                type != null && type.FullName == "NpcWeekly.Eleanor" && name.StartsWith("<CreateScav>", StringComparison.Ordinal) ||
                type != null && type.FullName == "MercDispatch.Visits" && name.StartsWith("<AddBriefChoices>", StringComparison.Ordinal);
        }
        static bool PaymentCallback(Delegate callback) {
            if (callback == null) return false;
            foreach (var action in callback.GetInvocationList()) {
                var method = action.Method; if (!KnownStory(method)) continue;
                bool pays;
                if (!payments.TryGetValue(method, out pays)) {
                    // Identify the actual native payment callback, not every callback
                    // generated by the story factory (stock, farewell, decline, etc.).
                    foreach (var code in PatchProcessor.GetOriginalInstructions(method)) {
                        var called = code.operand as MethodInfo;
                        var field=code.operand as FieldInfo;
                        if (code.opcode==System.Reflection.Emit.OpCodes.Stfld&&field!=null&&field.DeclaringType==typeof(PlayerStore)&&field.Name=="playerCash" ||
                            called != null && (called.DeclaringType == typeof(PlayerStore) && (called.Name == "ModCash"||called.Name=="PayMoney"||called.Name=="BuyOutStore"||called.Name=="TakeMortgage"||called.Name=="PayWeeklyMortgage") ||
                            called.DeclaringType == typeof(ModHelper) && called.Name == "AddCredit")) { pays = true; break; }
                    }
                    payments[method] = pays;
                }
                if (pays) return true;
            }
            return false;
        }
        static bool ContainsPayment(Dialogue line, HashSet<Dialogue> seen, bool current = false) {
            if (line == null || !seen.Add(line)) return false;
            // The current line's start action has already run. Only follow the
            // selected next-line chain; unchosen branches do not reserve funds.
            if (!current && PaymentCallback(line.startAction) || !line.isEndActionExecuted && PaymentCallback(line.endAction)) return true;
            // These two native quote screens capture the amount before selection.
            // Protect their displayed quote, without locking the whole story.
            if (current && line.choices != null) foreach (var choice in line.choices) {
                var action = choice.Item3;
                if (action != null && KnownStory(action.Method)) {
                    var target = action.Target;
                    if (target != null && (AccessTools.Field(target.GetType(), "value25") != null ||
                        AccessTools.Field(target.GetType(), "value50") != null || AccessTools.Field(target.GetType(), "need") != null)) return true;
                    // The inspector's bribe option is added once after CanPay, without
                    // an enabled predicate. Keep that native quote funded until selection.
                    if (action.Method.Name.StartsWith("<SecurityDialogInspectionLastLine>",StringComparison.Ordinal) &&
                        ContainsPayment(choice.Item2,new HashSet<Dialogue>())) return true;
                }
            }
            if (line.choices != null && line.choices.Count > 0) return false;
            return ContainsPayment(line.nextDialogue, seen);
        }
        internal static bool Pending {
            get {
                var s = Connection.Current; var ui = DialogUIManager.Instance;
                if (s == null || !s.IsHost || !s.Ready || WorldReplica.Applying || ui == null) return false;
                var seen = new HashSet<Dialogue>();
                if (ContainsPayment(ui.currentDialog, seen, true)) return true;
                var lines = ModReflect.Get<List<Dialogue>>(ui, "scheduledEndActionLines");
                if (lines != null) foreach (var line in lines) if (!line.isEndActionExecuted && PaymentCallback(line.endAction)) return true;
                return false;
            }
        }
        internal static bool AllowSpending() {
            
            if (!Pending) return true;
            RemoteActions.PendingNote = "~SMC364~";
            if (RemoteActions.CurrentOwner < 0) RemoteActions.Notice(RemoteActions.PendingNote);
            return false;
        }
    }
    [HarmonyPatch(typeof(CurrentConverterHelper), "CanSupply")]
    internal static class ConverterPaymentGate {
        // Supply checks this before deducting cash. A blocked machine does not run.
        static void Postfix(ref bool __result) { if (__result && !CurrentConverterHelper.isNightCycle && DialoguePayment.Pending) __result = false; }
    }
}
